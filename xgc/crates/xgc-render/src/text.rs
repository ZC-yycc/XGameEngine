/// 生成 NDC 顶点：每个点亮像素一个四边形；返回空网格表示无可见字符。
pub fn text_mesh(text: &str, origin: [f32; 2], pixel_size: f32, viewport: [f32; 2]) -> Mesh {
    let pixel = pixel_size.max(1.0);
    let advance = pixel * 6.0;
    let viewport_w = viewport[0].max(1.0);
    let viewport_h = viewport[1].max(1.0);
    let mut positions = Vec::new();
    let mut cursor = origin[0];
    let mut line = origin[1];
    for ch in text.chars() {
        if ch == '\n' {
            cursor = origin[0];
            line += pixel * 8.0;
            continue;
        }
        let Some(rows) = glyph(ch) else {
            cursor += advance;
            continue;
        };
        for (row, bits) in rows.iter().enumerate() {
            for col in 0..5 {
                if bits & (1 << (4 - col)) == 0 {
                    continue;
                }
                let x = cursor + col as f32 * pixel;
                let y = line + row as f32 * pixel;
                push_quad(&mut positions, [x, y, pixel, pixel], viewport_w, viewport_h);
            }
        }
        cursor += advance;
    }
    Mesh::new(positions, Vec::new())
}

fn push_quad(positions: &mut Vec<[f32; 3]>, rect: [f32; 4], vw: f32, vh: f32) {
    let x0 = rect[0] * 2.0 / vw - 1.0;
    let x1 = (rect[0] + rect[2]) * 2.0 / vw - 1.0;
    let y0 = 1.0 - rect[1] * 2.0 / vh;
    let y1 = 1.0 - (rect[1] + rect[3]) * 2.0 / vh;
    positions.extend_from_slice(&[
        [x0, y0, 0.0],
        [x1, y0, 0.0],
        [x1, y1, 0.0],
        [x0, y0, 0.0],
        [x1, y1, 0.0],
        [x0, y1, 0.0],
    ]);
}
